package com.round13.backend.domain;

/**
 * Статус пользователя системы.
 */
public enum UserStatus {

    /**
     * Пользователь активен и имеет полный доступ к функционалу.
     */
    ACTIVE,

    /**
     * Пользователь зарегистрирован, но не завершил обязательный онбординг профиля.
     * Используется для пользователей, созданных через Telegram.
     */
    PROFILE_INCOMPLETE,

    /**
     * Пользователь заблокирован и не может проходить аутентификацию.
     */
    BLOCKED
}
